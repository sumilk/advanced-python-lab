"""Streamz — a lazy data pipeline.

Read README.md in this directory for the full specification.

    uv run learn.py projects test streamz
"""
from __future__ import annotations

import itertools
from collections import deque


class StreamConsumed(RuntimeError):
    """Raised when a stream is iterated a second time."""


class Stream:
    """A lazy, single-use pipeline over an iterator.

    Every transformation returns a NEW Stream wrapping a generator over this
    one. Nothing is computed until a terminal method pulls.
    """

    def __init__(self, iterable):
        ...

    # -- construction ------------------------------------------------------
    @classmethod
    def of(cls, iterable):
        ...

    @classmethod
    def counter(cls, start=0, step=1):
        ...

    @classmethod
    def repeat(cls, value, times=None):
        ...

    # -- protocol ----------------------------------------------------------
    def __iter__(self):
        ...

    def __next__(self):
        ...

    def __or__(self, stage):
        ...

    # -- transformations (must stay lazy) ---------------------------------
    def map(self, fn): ...
    def filter(self, pred): ...
    def reject(self, pred): ...
    def flat_map(self, fn): ...
    def take(self, n): ...
    def drop(self, n): ...
    def take_while(self, pred): ...
    def drop_while(self, pred): ...
    def distinct(self, key=None): ...
    def enumerate(self, start=0): ...
    def window(self, n): ...
    def chunk(self, n): ...
    def peek(self, fn): ...
    def scan(self, fn, initial): ...
    def zip_with(self, other): ...
    def map_safe(self, fn, on_error=None): ...

    # -- terminals (consume the stream) -----------------------------------
    def to_list(self): ...
    def to_tuple(self): ...
    def to_set(self): ...
    def first(self, default=None): ...
    def last(self, default=None): ...
    def count(self): ...
    def sum(self): ...
    def min(self, key=None): ...
    def max(self, key=None): ...
    def reduce(self, fn, initial): ...
    def any(self, pred=bool): ...
    def all(self, pred=bool): ...
    def for_each(self, fn): ...
    def group_by(self, key): ...
    def partition(self, pred): ...
